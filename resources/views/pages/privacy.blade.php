<h1>隱私權政策</h1>
<div class="prose policy">
    <p>對於您使用本網站服務所留下的個人資料，中華基督教網路發展協會（以下稱「本協會」）基於對隱私權的尊重，將儘可能予以保護。以下說明愛諾園收集哪些資料、誰看得到、怎麼保護。</p>

    <h2>我們收集的資料</h2>
    <ul>
        <li>註冊資料：電子郵件、暱稱、性別、出生年、密碼（只存加密後的雜湊，任何人都看不到原本的密碼）。</li>
        <li>手機號碼：用來做手機認證，不會顯示給其他會員。</li>
        <li>個人資料、自我介紹、戀愛履歷、日記、照片、紙條、禮物等您在網站上留下的內容。</li>
        <li>真實姓名、住家電話（可以不填）：只有管理員看得到，不會顯示在交友檔案上。</li>
        <li>身份認證的資料：職業 Email、身分證明文件和教會週報的照片。照片只有管理員看得到，審核完就會刪掉。</li>
    </ul>

    <h2>誰看得到</h2>
    <ul>
        <li>交友檔案、公開的日記、相簿和通過審核的大頭照：登入的會員看得到。不公開的日記只有您自己看得到。</li>
        <li>生日只用來提醒您的好友「生日快到了」，不會顯示日期；年齡只顯示年齡層。</li>
        <li>紙條只有您和對方看得到。管理員為了處理檢舉、維護網站運作，可以查看會員發佈的內容。</li>
        <li>封鎖對方後，對方就看不到您的檔案、日記和照片。</li>
    </ul>

    <h2>我們不會做的事</h2>
    <ul>
        <li>不會把您的個人資料賣給或提供給其他人，除非依法律規定必須提供。</li>
        <li>不會用您的職業 Email 做認證以外的事，也不會聯絡您的公司（學校）。</li>
    </ul>

    <h2>您可以做的事</h2>
    <ul>
        <li>隨時修改您的資料；到「帳號設定」關掉 Email 通知或推播、暫停帳號，或註銷帳號。</li>
        <li>註銷帳號後，您的個人資料、照片、日記都會刪掉；您傳給別人的紙條會留在對方那邊，作為對方的紀錄。</li>
        <li>對隱私有任何問題，請寫信到 <a href="mailto:{{ config('loveuno.contact_email') }}">{{ config('loveuno.contact_email') }}</a>。</li>
    </ul>
</div>
