    public function run(): void
    {
        DB::transaction(function () {
            User::where('is_demo', true)->delete(); // profiles、diaries 會跟著刪（cascade）

            $users = [];
            foreach (self::MEMBERS as $i => [$name, $gender, $year, $place, $job, $intro, $hope]) {
                $user = User::create([
                    'name' => $name,
                    'email' => sprintf('demo%02d@loveuno-demo.invalid', $i + 1),
                    'password' => Str::random(48),
                    'is_demo' => true,
                ]);
                Profile::create([
                    'user_id' => $user->id,
                    'gender' => $gender,
                    'birth_year' => $year,
                    'live_place' => $place,
                    'job' => $job,
                    'church' => '',
                    'church_visible' => false,
                    'intro' => $intro,
                    'hope' => $hope,
                ]);
                $users[] = $user;
            }

            // 日記分給前幾位會員，日期往前排；最後一篇設成不公開，展示「只有自己看得到」
            $day = now()->startOfDay();
            foreach (self::DIARIES as $i => [$title, $body]) {
                Diary::create([
                    'user_id' => $users[$i % count($users)]->id,
                    'title' => $title,
                    'body' => $body,
                    'visibility' => $i === count(self::DIARIES) - 1 ? 'private' : 'public',
                    'published_on' => $day->copy()->subDays($i * 2),
                ]);
            }
        });
    }
